function textToAsciiArt(text) {
  const lines = ['', '', '', '', ''];

  for (let i = 0; i < text.length; i++) {
    const char = text[i];
    const glyph = FONT[char] || FONT[' '];

    for (let row = 0; row < 5; row++) {
      if (i > 0) {
        lines[row] += ' '; // 字符间距
      }
      lines[row] += glyph[row];
    }
  }

  return lines.join('\n');
}
