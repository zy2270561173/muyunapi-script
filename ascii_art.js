// ==MuYunAPI==
// @name         ASCII字符画
// @slug         ascii_art
// @description  将输入文字转换为3x5点阵ASCII字符画
// @category     6
// @method       GET
// @requireAuth  false
// @isFree       true
// @theme        both
// @params       [{"name":"text","type":"string","required":true,"description":"要转换的文字（支持英文大写字母、数字和部分符号）","example":"HELLO"}]
// @response     {"code":200,"message":"success","data":{"text":"HELLO","art":" #   # \n# # # # \n#####   \n#   #   \n#   #   "}}
// ==/MuYunAPI==

module.exports = {
  async execute(slug, params, req) {
    const text = (params.text || '').toUpperCase();

    if (!text) {
      return { code: 400, message: '缺少必填参数: text', data: null };
    }

    try {
      const art = textToAsciiArt(text);

      return {
        code: 200,
        message: 'success',
        data: {
          text,
          art,
        },
      };
    } catch (e) {
      return { code: 500, message: '转换失败: ' + e.message, data: null };
    }
  },
};

